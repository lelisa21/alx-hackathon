// End-to-end smoke test of the tutor in all three languages.
//
//   node scripts/smoke-ask.mjs [http://localhost:5173] [--cloud]
//
// Creates a session per language through the public API (as the widget does),
// asks representative questions, and prints the reply kind, provider-agnostic
// answer text and citation. --cloud records remote-AI consent for the session.
// Exits non-zero if any reply kind differs from the expected one.
const base = (
  process.argv.find((arg) => /^https?:/u.test(arg)) ?? "http://localhost:5173"
).replace(/\/$/u, "");
const cloud = process.argv.includes("--cloud");
const key = process.env.DIMTS_LOCAL_WIDGET_KEY ?? "local-widget-public-id";
const consentVersion = process.env.DIMTS_AI_CONSENT_VERSION ?? "remote-ai-v1";

const questions = {
  en: [
    "What score do I need to pass a course?",
    "How do I continue where I left off?",
    "What is the pacing boost?",
    "How do I verify content generated by AI?",
    "What modules are in VA-1?",
    // Asking for a person must escalate, never answer from content.
    { text: "How do I talk to a real person?", expect: "escalation" },
  ],
  am: [
    "ኮርስ ለማለፍ ምን ያህል ውጤት ያስፈልገኛል?",
    "ካቆምኩበት እንዴት እቀጥላለሁ?",
    "የፍጥነት ማበረታቻ ምንድን ነው?",
    "ምናባዊ ረዳት ማለት ምንድን ነው?",
  ],
  om: [
    "Koorsii darbuuf qabxii hammamii barbaada?",
    "Jajjabeessi saffisaa maali?",
    "Gargaaraan dijitaalaa maali?",
    "Dimts Telegram irratti fayyadamuu nan danda'aa?",
  ],
};

let failures = 0;
for (const [lang, list] of Object.entries(questions)) {
  const session = await fetch(`${base}/v1/sessions`, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      origin: base,
      "x-dimts-key": key,
    },
    body: JSON.stringify({
      lang,
      ...(cloud ? { cloudOk: true, consentVersion } : {}),
    }),
  }).then((response) => response.json());
  if (!session.sessionToken) {
    console.log(`${lang}: session failed`, session);
    failures += list.length;
    continue;
  }
  for (const [index, item] of list.entries()) {
    const { text, expect = "answer" } =
      typeof item === "string" ? { text: item } : item;
    const started = performance.now();
    const reply = await fetch(`${base}/v1/ask`, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        origin: base,
        authorization: `Bearer ${session.sessionToken}`,
      },
      body: JSON.stringify({
        sessionId: session.sessionId,
        clientMsgId: `smoke-${lang}-${index}-${Date.now()}`,
        lang,
        text,
        via: "text",
      }),
    }).then((response) => response.json());
    const ms = Math.round(performance.now() - started);
    if (reply.kind !== expect) failures += 1;
    const cite = reply.citations?.[0];
    console.log(
      `[${lang}] ${reply.kind.padEnd(8)} ${String(ms).padStart(5)}ms  Q: ${text}\n` +
        `         A: ${reply.text}\n` +
        (cite ? `         ↳ ${cite.label} ${cite.url}\n` : ""),
    );
  }
}
console.log(
  failures
    ? `${failures} question(s) did not get the expected reply`
    : "all questions got the expected reply",
);
process.exitCode = failures ? 1 : 0;
